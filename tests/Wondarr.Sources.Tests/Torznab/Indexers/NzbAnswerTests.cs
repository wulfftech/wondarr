using System.Net;
using System.Text;
using FluentAssertions;
using Wondarr.Core.Domain;
using Wondarr.Core.Logging;
using Wondarr.Core.Sources;
using Wondarr.Sources.Torznab.Indexers;
using Xunit;

namespace Wondarr.Sources.Tests.Torznab.Indexers;

/// <summary>
/// What an indexer answers instead of an NZB when its daily download quota is spent: told apart from
/// a real NZB, worded for the user, and kept free of secrets. Plus the status the Newznab client puts
/// on a failed download, which is how the search tells a 429 or a 403 from a dropped connection.
/// </summary>
public sealed class NzbAnswerTests
{
    private const string DogLimit = "You already reached your daily restriction of 10 downloads.";

    private const string WebPage = "The indexer answered with a web page, not an NZB.";

    private static readonly Func<string, string> NoRedaction = text => text;

    // U+FEFF: the byte order mark some indexers put in front of a document.
    private static readonly string Bom = new((char)0xFEFF, 1);

    public static TheoryData<string> RealNzbs() => new()
    {
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<nzb xmlns=\"http://www.newzbin.com/DTD/2003/nzb\"><file subject=\"x\"/></nzb>",
        Bom + "  \r\n<?xml version=\"1.0\" encoding=\"UTF-8\"?><nzb xmlns=\"http://www.newzbin.com/DTD/2003/nzb\"/>",
        "<nzb xmlns=\"http://www.newzbin.com/DTD/2003/nzb\"><file subject=\"x\"/></nzb>",
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!DOCTYPE nzb PUBLIC \"-//newzBin//DTD NZB 1.1//EN\" \"http://www.newzbin.com/DTD/nzb/nzb-1.1.dtd\">\n<nzb xmlns=\"http://www.newzbin.com/DTD/2003/nzb\"/>",

        // No XML declaration: a comment first, or the DOCTYPE first. The root is what counts.
        "<!-- generated by an indexer -->\n<nzb xmlns=\"http://www.newzbin.com/DTD/2003/nzb\"><file subject=\"x\"/></nzb>",
        "<!DOCTYPE nzb PUBLIC \"-//newzBin//DTD NZB 1.1//EN\" \"http://www.newzbin.com/DTD/nzb/nzb-1.1.dtd\">\n<nzb xmlns=\"http://www.newzbin.com/DTD/2003/nzb\"/>",
        Bom + "\r\n<!-- c --><!DOCTYPE nzb><nzb/>",
    };

    public static TheoryData<string> WebPages() => new()
    {
        "<!DOCTYPE html>\n<html><head><title>Maintenance</title></head><body>Back soon</body></html>",
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!DOCTYPE html PUBLIC \"-//W3C//DTD XHTML 1.0 Strict//EN\" \"http://www.w3.org/TR/xhtml1/DTD/xhtml1-strict.dtd\">\n<html xmlns=\"http://www.w3.org/1999/xhtml\"><body>Back soon</body></html>",
        "<?xml version=\"1.0\"?><rss version=\"2.0\"><channel><title>x</title></channel></rss>",
        "<html><body>unclosed",
        "<!-- an unfinished comment",
    };

    [Theory]
    [MemberData(nameof(RealNzbs))]
    public void A_document_whose_root_is_nzb_is_accepted_whatever_comes_before_it(string nzb)
    {
        var verdict = NzbAnswer.Check(Encoding.UTF8.GetBytes(nzb), NoRedaction);

        verdict.Kind.Should().Be(NzbAnswerKind.Nzb);
        verdict.IsNzb.Should().BeTrue();
        NzbAnswer.IsNzb(Encoding.UTF8.GetBytes(nzb)).Should().BeTrue();
    }

    [Theory]
    [MemberData(nameof(WebPages))]
    public void Markup_whose_root_is_not_nzb_is_a_web_page_and_a_refusal_with_a_fixed_sentence(string markup)
    {
        var verdict = NzbAnswer.Check(Encoding.UTF8.GetBytes(markup), NoRedaction);

        verdict.Kind.Should().Be(NzbAnswerKind.AccountRefusal);
        verdict.Text.Should().Be(WebPage, "the markup itself is never shown");
        NzbAnswer.IsNzb(Encoding.UTF8.GetBytes(markup)).Should().BeFalse();
    }

    [Fact]
    public void A_plain_sentence_is_the_indexers_words_and_refuses_the_account()
    {
        var verdict = NzbAnswer.Check(Encoding.UTF8.GetBytes(DogLimit), NoRedaction);

        verdict.Kind.Should().Be(NzbAnswerKind.AccountRefusal);
        verdict.Text.Should().Be(DogLimit);
    }

    [Theory]
    [InlineData("100", NzbAnswerKind.AccountRefusal)]
    [InlineData("102", NzbAnswerKind.AccountRefusal)]
    [InlineData("199", NzbAnswerKind.AccountRefusal)]
    [InlineData("200", NzbAnswerKind.ReleaseFailure)]
    [InlineData("201", NzbAnswerKind.ReleaseFailure)]
    [InlineData("299", NzbAnswerKind.ReleaseFailure)]
    [InlineData("300", NzbAnswerKind.ReleaseFailure)]
    [InlineData("399", NzbAnswerKind.ReleaseFailure)]
    [InlineData("400", NzbAnswerKind.ReleaseFailure)]
    [InlineData("500", NzbAnswerKind.AccountRefusal)]
    [InlineData("501", NzbAnswerKind.AccountRefusal)]
    [InlineData("599", NzbAnswerKind.AccountRefusal)]
    [InlineData("600", NzbAnswerKind.ReleaseFailure)]
    [InlineData("900", NzbAnswerKind.AccountRefusal)]
    [InlineData("910", NzbAnswerKind.AccountRefusal)]
    [InlineData("999", NzbAnswerKind.AccountRefusal)]
    [InlineData("1000", NzbAnswerKind.ReleaseFailure)]
    [InlineData("-102", NzbAnswerKind.ReleaseFailure)]
    [InlineData("soon", NzbAnswerKind.ReleaseFailure)]
    [InlineData("", NzbAnswerKind.ReleaseFailure)]
    public void A_newznab_error_document_refuses_the_account_only_for_an_account_level_code(string code, NzbAnswerKind expected)
    {
        var body = $"<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<error code=\"{code}\" description=\"Words from the indexer\"/>";

        var verdict = NzbAnswer.Check(Encoding.UTF8.GetBytes(body), NoRedaction);

        verdict.Kind.Should().Be(expected);
        verdict.Text.Should().Be("Words from the indexer");
    }

    [Fact]
    public void An_error_document_without_a_code_does_not_refuse_the_account()
    {
        NzbAnswer.Check(Encoding.UTF8.GetBytes("<error description=\"Daily limit\"/>"), NoRedaction)
            .Should().Be(new NzbVerdict(NzbAnswerKind.ReleaseFailure, "Daily limit"));
    }

    [Fact]
    public void An_error_document_without_a_description_gives_its_code_and_without_either_a_general_sentence()
    {
        NzbAnswer.Check(Encoding.UTF8.GetBytes("<?xml version=\"1.0\"?><error code=\"429\"/>"), NoRedaction).Text
            .Should().Be("The indexer answered error 429.");
        NzbAnswer.Check(Encoding.UTF8.GetBytes("<?xml version=\"1.0\"?><error/>"), NoRedaction).Text
            .Should().Be("The indexer did not answer with an NZB.");
    }

    [Fact]
    public void An_error_document_without_the_xml_declaration_is_read_too()
    {
        NzbAnswer.Check(Encoding.UTF8.GetBytes("<error code=\"100\" description=\"Incorrect user credentials\"/>"), NoRedaction)
            .Should().Be(new NzbVerdict(NzbAnswerKind.AccountRefusal, "Incorrect user credentials"));
    }

    [Fact]
    public void An_error_document_is_found_after_a_bom_and_whitespace()
    {
        var body = Bom + "\r\n  <?xml version=\"1.0\"?><error code=\"100\" description=\"Incorrect user credentials\"/>";

        NzbAnswer.Check(Encoding.UTF8.GetBytes(body), NoRedaction)
            .Should().Be(new NzbVerdict(NzbAnswerKind.AccountRefusal, "Incorrect user credentials"));
    }

    [Theory]
    [InlineData("")]
    [InlineData("   \r\n ")]
    public void An_empty_answer_has_a_general_sentence(string body)
    {
        NzbAnswer.Check(Encoding.UTF8.GetBytes(body), NoRedaction)
            .Should().Be(new NzbVerdict(NzbAnswerKind.AccountRefusal, "The indexer did not answer with an NZB."));
    }

    [Theory]
    [InlineData("<?xml version=\"1.0\"?><")]
    [InlineData("<?xml version=\"1.0\"?>")]
    [InlineData("<nzb xmlns=\"http://www.newzbin.com/DTD/2003/nzb\"><file subject=\"cut off")]
    public void A_document_that_starts_like_an_nzb_but_is_broken_is_left_to_the_nzb_parser(string body)
    {
        NzbAnswer.Check(Encoding.UTF8.GetBytes(body), NoRedaction).Kind.Should().Be(NzbAnswerKind.Nzb);
    }

    [Fact]
    public void The_text_is_one_line_and_at_most_200_characters()
    {
        var body = "Line one\r\nline\ttwo   " + new string('x', 400);

        var text = NzbAnswer.Check(Encoding.UTF8.GetBytes(body), NoRedaction).Text;

        text.Should().StartWith("Line one line two xxx");
        text.Length.Should().Be(200);
        text.Should().NotContainAny("\r", "\n", "\t");
    }

    [Fact]
    public void A_registered_secret_is_removed_before_the_text_is_cut()
    {
        const string key = "S3cretIndexerKey";
        var secrets = new SecretRegistry();
        secrets.Register(key);

        // The key runs from character 186 to 201: cut first, half of it would survive redaction.
        var body = new string('a', 185) + " " + key + " is not valid";

        var text = NzbAnswer.Check(Encoding.UTF8.GetBytes(body), secrets.Redact).Text;

        text.Should().NotContain("S3cret").And.NotContain("Key");
        text.Should().Contain("(removed)");
        text.Length.Should().BeLessThanOrEqualTo(200);
    }

    [Fact]
    public void A_key_across_the_old_1024_byte_cut_is_redacted_whole()
    {
        const string key = "S3cretIndexerKey";
        var secrets = new SecretRegistry();
        secrets.Register(key);

        // Whitespace is collapsed, so the key is near the start of what is shown while its bytes run
        // from 1018 to 1034: cut at 1024 bytes first, "S3cret" would have survived the redaction.
        var body = "Refused " + new string(' ', 1010) + key + " is not valid";

        var text = NzbAnswer.Check(Encoding.UTF8.GetBytes(body), secrets.Redact).Text;

        text.Should().Be("Refused (removed) is not valid");
    }

    [Fact]
    public void A_key_near_the_end_of_a_6_KiB_body_is_redacted()
    {
        const string key = "S3cretIndexerKey";
        var secrets = new SecretRegistry();
        secrets.Register(key);

        var tail = key + " is not valid";
        var body = "Rejected" + new string(' ', (6 * 1024) - "Rejected".Length - tail.Length) + tail;

        body.Length.Should().Be(6 * 1024);

        var text = NzbAnswer.Check(Encoding.UTF8.GetBytes(body), secrets.Redact).Text;

        text.Should().Be("Rejected (removed) is not valid");
    }

    [Fact]
    public void A_percent_encoded_key_in_a_refusal_that_quotes_the_request_is_redacted()
    {
        const string key = "Ab+c/d=Ef12";
        var secrets = new SecretRegistry();
        secrets.Register(key);

        // Whitespace in front of the quote, so the key is past the old 1024-byte cut as well.
        var body = "Refused" + new string(' ', 2000) + "Bad request: /api?t=get&k=Ab%2Bc%2Fd%3DEf12&q=x";

        var text = NzbAnswer.Check(Encoding.UTF8.GetBytes(body), secrets.Redact).Text;

        text.Should().Be("Refused Bad request: /api?t=get&k=(removed)&q=x");
    }

    [Theory]
    [InlineData(1024)]
    [InlineData(6 * 1024)]
    [InlineData(20 * 1024)]
    public void What_is_shown_is_still_at_most_200_characters_however_long_the_body_is(int length)
    {
        var body = string.Concat(Enumerable.Repeat("Sorry, no. ", (length / 11) + 1));

        var text = NzbAnswer.Check(Encoding.UTF8.GetBytes(body), NoRedaction).Text;

        NzbAnswer.MaxTextLength.Should().Be(200);
        text.Length.Should().Be(200);
        text.Should().StartWith("Sorry, no. Sorry, no.");
    }

    [Fact]
    public void An_api_key_in_a_url_the_indexer_quotes_is_removed_even_when_nobody_registered_it()
    {
        var body = "Bad request: https://dog.example/api?t=get&apikey=abcdef0123456789&id=1";

        var text = NzbAnswer.Check(Encoding.UTF8.GetBytes(body), CleanseLogMessage.Cleanse).Text;

        text.Should().NotContain("abcdef0123456789");
    }

    [Theory]
    [InlineData(HttpStatusCode.TooManyRequests)]
    [InlineData(HttpStatusCode.Forbidden)]
    [InlineData(HttpStatusCode.InternalServerError)]
    public async Task The_newznab_client_puts_the_status_on_a_failed_download(HttpStatusCode status)
    {
        var handler = new RecordingHandler(_ => new HttpResponseMessage(status));
        var client = TorznabTest.NewznabClient(handler);

        var act = () => client.DownloadAsync(
            TorznabFixtures.Indexer(type: "newznab", protocol: DownloadProtocol.Usenet),
            Release("https://indexer.example/getnzb/1.nzb"),
            CancellationToken.None);

        var exception = (await act.Should().ThrowAsync<IndexerException>()).Which;
        exception.StatusCode.Should().Be(status);
        exception.Message.Should().Be($"The indexer answered {(int)status}.");
    }

    [Fact]
    public async Task The_newznab_client_hands_a_plain_text_answer_back_as_it_is_and_leaves_judging_it_to_the_search()
    {
        var handler = new RecordingHandler(_ => new HttpResponseMessage(HttpStatusCode.OK) { Content = new StringContent(DogLimit) });
        var client = TorznabTest.NewznabClient(handler);

        var download = await client.DownloadAsync(
            TorznabFixtures.Indexer(type: "newznab", protocol: DownloadProtocol.Usenet),
            Release("https://indexer.example/getnzb/1.nzb"),
            CancellationToken.None);

        Encoding.UTF8.GetString(download.Content!).Should().Be(DogLimit);
    }

    [Fact]
    public async Task A_dropped_connection_carries_no_status()
    {
        var handler = new RecordingHandler(_ => throw new HttpRequestException("boom"));
        var client = TorznabTest.NewznabClient(handler);

        var act = () => client.DownloadAsync(
            TorznabFixtures.Indexer(type: "newznab", protocol: DownloadProtocol.Usenet),
            Release("https://indexer.example/getnzb/1.nzb"),
            CancellationToken.None);

        var exception = (await act.Should().ThrowAsync<IndexerException>()).Which;
        exception.StatusCode.Should().BeNull();
    }

    private static IndexerRelease Release(string downloadUrl) => new(
        "Daft Punk - Discovery [2001] [FLAC]",
        "example-1",
        downloadUrl,
        null,
        null,
        null,
        null,
        null,
        null,
        null,
        [],
        null,
        null,
        DownloadProtocol.Usenet,
        1,
        "Example Indexer",
        null);
}
